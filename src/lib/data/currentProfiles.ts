export type CurrentProfile = { id:string; reserve_profile:ReserveProfileV2; redemption_profile:RedemptionProfileV2; };
const rawProfiles = [...profileData,...profileBatchAData,...profileBatchBData,...profileBatchCData,...profileBatchDData,...profileBatchEData,...profileBatchFData,...profileBatchGData,...profileBatchHData,...profileBatchIData,...profileBatchJData,...profileBatchKData,...profileBatchLData,...profileBatchMData,...profileBatchNData,...profileBatchOData,...profileBatchPData,...profileBatchQData,...profileBatchRData,...profileBatchSData,...profileBatchTData,...profileBatchUData,...profileBatchVData,...profileBatchWData,...profileBatchXData,...profileBatchYData,...profileBatchZData,...profileBatchAAData,...profileBatchABData,...profileBatchACData,...profileBatchADData,...profileBatchAEData,...profileBatchAFData,...profileBatchAGData,...profileBatchAHData,...profileBatchAIData,...profilePr354Data,...profilePr355Data] as CurrentProfile[];
const byId = new Map(rawProfiles.map((row) => [row.id,row] as const));
const profiles = [...byId.values()];
const clone = (row:CurrentProfile):CurrentProfile => ({...row,reserve_profile:{...row.reserve_profile,backing_types:[...row.reserve_profile.backing_types],evidence_ids:[...(row.reserve_profile.evidence_ids ?? [])]},redemption_profile:{...row.redemption_profile,jurisdiction_restrictions:[...(row.redemption_profile.jurisdiction_restrictions ?? [])],evidence_ids:[...(row.redemption_profile.evidence_ids ?? [])]}});
export function getCurrentProfiles():CurrentProfile[] { return profiles.map(clone); }
export function getCurrentProfile(id:string):CurrentProfile|undefined { const row=byId.get(id); return row?clone(row):undefined; }
