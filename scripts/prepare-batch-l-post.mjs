import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=(f)=>JSON.parse(fs.readFileSync(path.join(root,f),'utf8'));
const write=(f,v)=>fs.writeFileSync(path.join(root,f),JSON.stringify(v,null,2)+'\n');
const file='docs/migration/registry-v3-baseline.json';
const baseline=read(file);
const stats=read(baseline.generated_stats);
const audit=read(baseline.integrity_audit);
const launch=read(baseline.quality_queues.launch_date);
const terminal=read(baseline.quality_queues.terminal_date);
const reserve=read(baseline.quality_queues.reserve_report_applicability);
baseline.baseline_id='sog_registry_v3_quality_75_2026_06_21';
baseline.recorded_at='2026-06-21';
baseline.data_checkpoint_commit='batch-l-current-stable-assets';
baseline.expected_counts={...stats.registry};
baseline.expected_coverage=Object.fromEntries(Object.entries(audit.coverage).map(([key,value])=>[key,value.covered]));
baseline.quality={canonical_assets:stats.registry.stablecoins,candidate_promotions:audit.candidate_promotions.promoted,pending_candidates:audit.candidate_promotions.pending,critical_findings:audit.findings.critical.length,warnings:audit.findings.warnings.length,canonical_name_collisions:audit.identity.canonical_name_collisions,alias_collision_warnings:audit.identity.alias_collision_warnings,stale_or_missing_last_verified:audit.quality.stale_or_missing_last_verified,all_unknown_income_profiles:audit.quality.all_unknown_income_profiles,launch_date_unresolved:launch.expected_total,terminal_date_unresolved:terminal.expected_total,reserve_report_applicability_queue:reserve.expected_total,reserve_report_not_applicable_by_design:reserve.category_counts.not_applicable_by_design,reserve_report_source_status_unresolved:reserve.category_counts.source_status_unresolved,reserve_report_expected_but_missing:reserve.category_counts.report_expected_but_missing};
baseline.policy.production_parity_deferred_until_cloudflare_access_returns=false;
baseline.policy.production_parity_required_at_75=true;
write(file,baseline);
console.log('Batch L quality baseline prepared');
